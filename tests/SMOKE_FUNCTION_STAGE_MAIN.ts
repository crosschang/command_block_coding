/** 단계 진단 사용자 프로그램: JavaScript 전체 교체, 블록 변환 금지.
 * ff2 -> ff13 -> ff26. 각 DONE 뒤 다음 입력. 처음부터 TRACE ON.
 * ffwhere는 저장값만 읽지만, 같은 채팅 처리 경로이므로 무응답일 수 있다.
 * traceoff / traceon은 추가 진단 출력을 끄거나 켠다. 시간 비교용이 아니다.
 */
MCFunctionOrderedPreview.setTraceEnabled(true)
player.onChat("ffwhere", function () {
    let stage = MCFunctionOrderedPreview.lastExecutionStage()
    let clock = MCFunctionOrderedPreview.lastClockStage()
    let id = MCFunctionOrderedPreview.lastRequestId()
    let ack = MCFunctionOrderedPreview.lastAckStatus()
    player.say("FF_WHERE stage=" + stage + " clock=" + clock + " id=" + id + " ack=" + ack)
})
player.onChat("traceon", function () { MCFunctionOrderedPreview.setTraceEnabled(true) })
player.onChat("traceoff", function () { MCFunctionOrderedPreview.setTraceEnabled(false) })
