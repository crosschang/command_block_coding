(function(){
    let direct=node(MCFunctionAST.CommandKind.Say);
    let execute=node(MCFunctionAST.CommandKind.Execute);
    let raw=node(MCFunctionAST.CommandKind.Raw);
    let summon:MCFunctionAST.SummonCommand={kind:MCFunctionAST.CommandKind.Summon,form:MCFunctionAST.SummonForm.Advanced,orientation:{kind:MCFunctionAST.SummonOrientationKind.Facing}};
    let timeQuery:MCFunctionAST.TimeCommand={kind:MCFunctionAST.CommandKind.Time,action:MCFunctionAST.TimeAction.Query};
    let gameruleQuery:MCFunctionAST.GameRuleCommand={kind:MCFunctionAST.CommandKind.Gamerule,action:MCFunctionAST.GameRuleAction.Query};
    let gameruleList:MCFunctionAST.GameRuleCommand={kind:MCFunctionAST.CommandKind.Gamerule,action:MCFunctionAST.GameRuleAction.List};
    let scoreList:MCFunctionAST.ScoreboardCommand={kind:MCFunctionAST.CommandKind.Scoreboard,action:MCFunctionAST.ScoreboardAction.PlayerList};
    let tagList:MCFunctionAST.TagCommand={kind:MCFunctionAST.CommandKind.Tag,action:MCFunctionAST.TagActionKind.List};
    let spawnAbs:MCFunctionAST.SpawnPointCommand={kind:MCFunctionAST.CommandKind.SpawnPoint,mode:MCFunctionAST.SpawnPointMode.TargetAt,position:{x:{mode:0},y:{mode:0},z:{mode:0}}};
    let spawnRel:MCFunctionAST.SpawnPointCommand={kind:MCFunctionAST.CommandKind.SpawnPoint,mode:MCFunctionAST.SpawnPointMode.TargetAt,position:{x:{mode:1},y:{mode:1},z:{mode:1}}};

    assert(MCFunctionRuntime.resolve(execute)===MCFunctionRuntime.Route.MakeCode,'default legacy off');
    RuntimeBridge.select(RuntimeBridge.Transport.CBX12Hex);
    assert(MCFunctionRuntime.resolve(direct)===MCFunctionRuntime.Route.Bridge,'CBX12 manual all');
    RuntimeBridge.select(RuntimeBridge.Transport.CBXCoreHex);
    assert(MCFunctionRuntime.resolve(direct)===MCFunctionRuntime.Route.Bridge,'CBXCORE manual all');
    RuntimeBridge.select(RuntimeBridge.Transport.CBXCoreSelective);
    assert(MCFunctionRuntime.resolve(direct)===MCFunctionRuntime.Route.Bridge,'Selective manual all');
    RuntimeBridge.select(RuntimeBridge.Transport.Auto);
    assert(MCFunctionRuntime.isAutomatic(),'auto selected');
    assert(MCFunctionCBX12Bridge.currentTransport()==='selective','auto uses selective transport');
    assert(MCFunctionRuntime.resolve(direct)===MCFunctionRuntime.Route.MakeCode,'auto direct');
    assert(MCFunctionRuntime.resolve(node(MCFunctionAST.CommandKind.SetBlock))===MCFunctionRuntime.Route.MakeCode,'auto setblock');
    assert(MCFunctionRuntime.resolve(execute)===MCFunctionRuntime.Route.Bridge,'auto modern execute bridge');
    assert(MCFunctionRuntime.resolve(raw)===MCFunctionRuntime.Route.Bridge,'raw bridge candidate');
    assert(MCFunctionRuntime.classify(summon)===MCFunctionRuntime.EvidenceClass.MakeCodeAdapter,'summon orientation emulated');
    assert(MCFunctionRuntime.resolve(summon)===MCFunctionRuntime.Route.MakeCode,'summon legacy adapter retained');
    assert(MCFunctionRuntime.classify(timeQuery)===MCFunctionRuntime.EvidenceClass.ReadbackPending,'time query pending');
    assert(MCFunctionRuntime.classify(gameruleQuery)===MCFunctionRuntime.EvidenceClass.ReadbackPending,'gamerule query pending');
    assert(MCFunctionRuntime.classify(gameruleList)===MCFunctionRuntime.EvidenceClass.ReadbackPending,'gamerule list pending');
    assert(MCFunctionRuntime.classify(scoreList)===MCFunctionRuntime.EvidenceClass.ReadbackPending,'scoreboard list pending');
    assert(MCFunctionRuntime.classify(tagList)===MCFunctionRuntime.EvidenceClass.ReadbackPending,'tag list pending');
    assert(MCFunctionRuntime.resolve(scoreList)===MCFunctionRuntime.Route.MakeCode,'no fake scoreboard live readback');
    assert(MCFunctionRuntime.resolve(spawnAbs)===MCFunctionRuntime.Route.MakeCode,'spawnpoint absolute historical direct');
    assert(MCFunctionRuntime.resolve(spawnRel)===MCFunctionRuntime.Route.Bridge,'spawnpoint relative candidate');
    assert(MCFunctionRuntime.classify(spawnRel)===MCFunctionRuntime.EvidenceClass.BridgeCandidate,'bridge candidate not pass');
    FunctionFile.allow=false;
    RuntimeBridge.select(RuntimeBridge.Transport.Original);
    assert(MCFunctionRuntime.isAutomatic(),'invalid nested selection is ignored');
    FunctionFile.allow=true;
    RuntimeBridge.select(RuntimeBridge.Transport.Original);
    assert(!MCFunctionRuntime.isAutomatic(),'auto switched off');
    assert(MCFunctionRuntime.resolve(execute)===MCFunctionRuntime.Route.MakeCode,'legacy restored');
    console.log('P1b HOST MOCK: 24 assertions PASS');
})();
